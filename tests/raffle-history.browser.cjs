// Run with a local HTTP server and Playwright available through NODE_PATH.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const base = process.env.PORTAL_TEST_URL || 'http://127.0.0.1:8000';
const record = (overrides = {}) => ({ version: 1, id: 'previous', name: 'Anterior', drawnAt: '2026-10-01T12:00:00.000Z', winner: { id: 'old', nickname: 'Nome da época' }, participants: [{ id: 'old', nickname: 'Nome da época' }], excluded: [], ...overrides });
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}/sorteio.html`);
    await page.locator('#raffle-form').waitFor({ state: 'visible' });
    await page.getByRole('button', { name: 'Desmarcar todos' }).click();
    assert.equal(await page.locator('#review').isDisabled(), true);
    await page.getByRole('checkbox').first().check();
    const selectedName = await page.getByRole('checkbox').first().evaluate(input => input.parentElement.innerText);
    await page.getByLabel('Identificação do sorteio').fill('Prêmio de teste');
    await page.locator('#review').click();
    await page.getByRole('button', { name: 'Sortear vencedor', exact: true }).click();
    assert.equal(await page.locator('#winner-name').innerText(), selectedName);
    const downloadPending = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Baixar resultado' }).click();
    const resultDownload = await downloadPending;
    const resultText = await fs.readFile(await resultDownload.path(), 'utf8');
    const result = JSON.parse(resultText);
    assert.equal(result.participants.length, 1);
    assert.ok(result.excluded.length > 0);
    assert.equal(result.winner.nickname, selectedName);
    assert.deepEqual(Object.keys(result.participants[0]).sort(), ['id', 'nickname']);
    let official = [record()];
    await page.route('**/data/raffles.json', route => route.fulfill({ json: official }));
    await page.goto(`${base}/historico-sorteios.html`);
    await page.locator('#official-history article').waitFor();
    assert.match(await page.locator('#official-history').innerText(), /Nome da época/);
    await page.locator('#history-tools summary').first().click();
    const upload = text => page.locator('#result-file').setInputFiles({ name: 'resultado.json', mimeType: 'application/json', buffer: Buffer.from(text) });
    await upload(resultText);
    await page.locator('#import-preview').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#download-history').isDisabled(), true);
    assert.equal(await page.locator('#official-history article').count(), 1);
    await page.getByLabel('Conferi o resultado', { exact: false }).check();
    const historyPending = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Baixar histórico atualizado' }).click();
    const historyDownload = await historyPending;
    assert.equal(historyDownload.suggestedFilename(), 'raffles.json');
    const merged = JSON.parse(await fs.readFile(await historyDownload.path(), 'utf8'));
    assert.equal(merged.length, 2);
    assert.deepEqual(merged.find(item => item.id === result.id), result);
    assert.deepEqual(merged.find(item => item.id === 'previous'), record());
    assert.equal(await page.locator('#official-history article').count(), 1, 'download never publishes');
    // Reject stale full-file exports if another result was published during review.
    official = [record({ id: 'other', name: 'Outra publicação', drawnAt: '2026-10-02T12:00:00.000Z' }), record()];
    await page.locator('#download-history').click();
    await page.getByRole('alert').filter({ hasText: 'histórico mudou' }).waitFor();
    assert.equal(await page.locator('#import-preview').isVisible(), false);
    await upload(JSON.stringify({ ...result, winner: { id: 'outsider', nickname: 'Outro' } }));
    await page.getByRole('alert').filter({ hasText: 'Vencedor' }).waitFor();
    assert.equal(await page.locator('#import-preview').isVisible(), false);
    // Simulate publication using browser routing only, never save invented draws to the repo.
    official = merged;
    await page.reload();
    await page.locator('#official-history article').nth(1).waitFor();
    await page.locator('#history-tools summary').first().click();
    await upload(resultText);
    await page.getByRole('alert').filter({ hasText: 'duplicado' }).waitFor();
    assert.equal(await page.locator('#import-preview').isVisible(), false);
    await page.locator('#official-history article').first().locator('summary').click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    await page.screenshot({ path: '.qa/history-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: '.qa/history-desktop.png', fullPage: true });
    official = [];
    await page.reload();
    await page.getByRole('status').filter({ hasText: 'Nenhum sorteio oficial' }).waitFor();
    await page.route('**/data/raffles.json', route => route.fulfill({ status: 500, body: 'error' }));
    await page.reload();
    await page.locator('#history-error').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#result-file').isDisabled(), true);
    await page.setViewportSize({ width: 320, height: 740 });
    await page.goto(`${base}/index.html`);
    assert.equal(await page.getByRole('navigation').getByRole('link', { name: 'Histórico de sorteios' }).count(), 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('Browser QA passed: draw/export/import/review/merge, snapshots, duplicates, stale history, invalid winner, empty/failing history, responsive navigation.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
